// The language every output uses: an explicit option, else BRIEF's `language`, else English.
export function projectLang(p, lang) {
  const code = String(lang || (p.brief && !p.brief.error ? p.brief.data?.language : '') || 'en').toLowerCase();
  return LANGS[code] ? code : 'en';
}

