// Renders openidea/ideas/INDEX.md. Output is deterministic (no timestamps) so that
// regenerating an unchanged project produces no git diff.
import { analyze, QUEUE_SIZE } from './analyze.mjs';

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderIndex(p, issues) {
  const a = analyze(p, issues);
  const out = [];
  out.push('# Ideas Index', '', '_Generated by `openidea index` from a scan of the filesystem. Do not edit by hand: regenerate it._', '');

  out.push('## Active ideas', '');
  if (a.active.length === 0) out.push('_None._');
  else {
    out.push('| id | status | type | category | updated | open gaps |', '| --- | --- | --- | --- | --- | --- |');
    const order = { ready: 0, captured: 1, parked: 2 };
    const rows = [...a.active].sort((x, y) => (order[x.data.status] ?? 9) - (order[y.data.status] ?? 9) || x.data.id.localeCompare(y.data.id));
    for (const i of rows) out.push(`| ${cell(i.data.id)} | ${cell(i.data.status)} | ${cell(i.data.type || 'feature')} | ${cell(i.data.category)} | ${cell(i.data.updated)} | ${a.gapsByIdea.get(i.data.id) || 0} |`);
  }
  out.push('', `${a.counts.archived} archived, ${a.counts.promoted} promoted (see \`ideas/archive/\` and \`ideas/promoted/\`).`, '');

  out.push('## Ready but not yet planned', '');
  out.push(a.readyUnplanned.length ? a.readyUnplanned.map((i) => `- ${i.data.id}`).join('\n') : '_None._', '');

  out.push('## Needs clarification', '');
  out.push(a.needsClarification.length ? a.needsClarification.map((i) => `- ${i.data.id}`).join('\n') : '_None._', '');

  out.push(`## Decision queue (top ${QUEUE_SIZE} open gaps)`, '');
  if (a.queue.length === 0) out.push('_No open gaps._');
  else {
    out.push('| gap | kind | impact | confidence | question |', '| --- | --- | --- | --- | --- |');
    for (const g of a.queue) out.push(`| ${cell(g.data.id)} | ${cell(g.data.kind)} | ${cell(g.data.impact)} | ${cell(g.data.confidence)} | ${cell(g.data.question)} |`);
    if (a.open.length > a.queue.length) out.push('', `${a.open.length - a.queue.length} more open gaps in \`gaps/\`.`);
  }
  out.push('');

  out.push('## Blueprint', '');
  if (!a.depth) out.push('_No blueprint yet. Run `/openidea:blueprint`._');
  else {
    const pct = a.depth.score === null ? 'n/a' : `${Math.round(a.depth.score * 100)}%`;
    out.push(`Depth: ${pct} (${a.depth.filled}/${a.depth.total} mandatory slots filled). Hidden assumptions: ${a.assumptions}.`);
  }
  out.push('');

  out.push('## Anomalies', '');
  const shown = issues.filter((i) => i.level !== 'info');
  out.push(shown.length ? shown.map((i) => `- **${i.level}** \`${i.code}\` ${i.file}: ${i.message}`).join('\n') : '_None._', '');
  return out.join('\n');
}
